/**
 * Extracts SVG inner markup for every lucide icon used by categories / content packs,
 * so category artwork can be composed as standalone SVG data-URIs (no React at runtime).
 * Run: node scripts/gen-art-glyphs.mjs
 */
import fs from "fs";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as Lucide from "lucide-react";
import { CATEGORIES } from "../src/data/categories.js";
import { AI_CONTENT_PACKS } from "../src/data/aiContentPacks.js";

const names = new Set(["Sparkles", "Star", "Heart", "Check", "BadgeCheck", "Clock", "ShieldCheck"]);
CATEGORIES.forEach((c) => names.add(c.icon));
Object.values(AI_CONTENT_PACKS).forEach((p) => {
  (p.services || []).forEach((s) => names.add(s[0]));
  (p.features || []).forEach((s) => names.add(s[0]));
});
try {
  const extra = await import("../src/data/categoryContent.js");
  Object.values(extra.CATEGORY_CONTENT || {}).forEach((p) => { (p.f || []).forEach((s) => names.add(s[0])); (p.sv || []).forEach((s) => names.add(s[0])); (p.p || []).forEach((g) => g[1].forEach((it) => names.add(it[5]))); });
} catch { /* optional */ }

const out = {};
const missing = [];
for (const n of [...names].sort()) {
  const Cmp = Lucide[n];
  if (!Cmp) { missing.push(n); continue; }
  const svg = renderToStaticMarkup(React.createElement(Cmp, { size: 24 }));
  const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  out[n] = inner;
}
fs.writeFileSync(
  new URL("../src/data/artGlyphs.js", import.meta.url),
  `/* AUTO-GENERATED by scripts/gen-art-glyphs.mjs — do not edit by hand. */\nexport const GLYPHS = ${JSON.stringify(out)};\n`
);
console.log("glyphs:", Object.keys(out).length, "missing:", missing.join(", ") || "none");
