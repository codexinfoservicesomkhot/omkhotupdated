/**
 * Regenerates src/components/common/bizIconMap.js — every lucide icon used by
 * categories, content packs and bespoke content, so BizIcon never falls back to Sparkles.
 * Run: node scripts/gen-bizicons.mjs
 */
import fs from "fs";
import * as Lucide from "lucide-react";
import { CATEGORIES } from "../src/data/categories.js";
import { AI_CONTENT_PACKS } from "../src/data/aiContentPacks.js";
import { CATEGORY_CONTENT } from "../src/data/categoryContent.js";

const cur = fs.readFileSync(new URL("../src/components/common/BizIcon.jsx", import.meta.url), "utf8");
const keep = new Set();
// keep whatever was already available (the icon picker in the editor uses it)
for (const m of cur.matchAll(/\b([A-Z][A-Za-z0-9]+)\b/g)) if (Lucide[m[1]] && typeof Lucide[m[1]] !== "string") keep.add(m[1]);
try { const prev = fs.readFileSync(new URL("../src/components/common/bizIconMap.js", import.meta.url), "utf8"); for (const m of prev.matchAll(/\b([A-Z][A-Za-z0-9]+)\b/g)) if (Lucide[m[1]]) keep.add(m[1]); } catch {}
CATEGORIES.forEach((c) => keep.add(c.icon));
Object.values(AI_CONTENT_PACKS).forEach((p) => { (p.services || []).forEach((s) => keep.add(s[0])); (p.features || []).forEach((s) => keep.add(s[0])); });
Object.values(CATEGORY_CONTENT).forEach((c) => { (c.f || []).forEach((s) => keep.add(s[0])); (c.sv || []).forEach((s) => keep.add(s[0])); (c.p || []).forEach((g) => g[1].forEach((it) => keep.add(it[5]))); });
["Sparkles", "Star", "Heart", "Check", "Phone", "MapPin", "Mail", "Clock", "ShieldCheck", "BadgeCheck"].forEach((n) => keep.add(n));
const names = [...keep].filter((n) => Lucide[n] && n !== "Icon" && !/^Lucide|Icon$/.test(n)).sort();
fs.writeFileSync(
  new URL("../src/components/common/bizIconMap.js", import.meta.url),
  `/* AUTO-GENERATED by scripts/gen-bizicons.mjs — do not edit by hand. */\nimport {\n  ${names.join(",\n  ")},\n} from "lucide-react";\n\nexport const ICONS = {\n  ${names.join(",\n  ")},\n};\n`
);
console.log("icons:", names.length);
