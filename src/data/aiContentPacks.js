/**
 * Content for a category = the base pack (services / about / menu…) overlaid with
 * the bespoke content in categoryContent.js (features, reviews, FAQs, stats, team,
 * CTA banner, and full packs for categories that had none).
 */
export const getContentPack = (categoryId) => {
  const base = AI_CONTENT_PACKS[categoryId] || AI_CONTENT_PACKS.other;
  const c = CATEGORY_CONTENT[categoryId];
  if (!c) return base;
  return {
    ...base,
    tagline: c.tag || base.tagline,
    about: c.about || base.about,
    services: c.sv || base.services,
    products: c.p || base.products,
    features: c.f || base.features,
    team: c.m || base.team,
    testimonials: c.t || base.testimonials,
    faqs: c.q || base.faqs,
    stats: c.s || base.stats,
    hours: c.hrs || base.hours,
    cta: c.cb || base.cta,
  };
};

/**
 * Real stock photos are only used where a photo set belongs to ONE category.
 * Anything shared (e.g. "dental" reusing the clinic photos) falls back to that
 * category's own generated artwork, so no two categories show the same images.
 */
const FAMILY_OWNERS = ["clinic", "gym", "cafe", "salon", "restaurant"];
const PHOTO_SETS = {};
FAMILY_OWNERS.forEach((id) => { const im = TEMPLATES[id]?.sample?.images; if (im?.hero) PHOTO_SETS[id] = im; });
Object.entries(CATEGORY_IMAGES).forEach(([id, im]) => { if (!PHOTO_SETS[id]) PHOTO_SETS[id] = im; });
const HERO_COUNT = {};
Object.values(PHOTO_SETS).forEach((im) => { HERO_COUNT[im.hero] = (HERO_COUNT[im.hero] || 0) + 1; });
const OWN_PHOTOS = {};
const claimed = new Set();
[...FAMILY_OWNERS, ...Object.keys(PHOTO_SETS)].forEach((id) => {
  const im = PHOTO_SETS[id];
  if (!im || claimed.has(im.hero) || OWN_PHOTOS[id]) return;
  claimed.add(im.hero);
  OWN_PHOTOS[id] = im;
});
void HERO_COUNT;

/** Unique stock photos for a category, or null → the renderer uses the category's artwork. */
export const getCategoryImages = (categoryId) => OWN_PHOTOS[categoryId] || null;
